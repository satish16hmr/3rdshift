export function getGenerationTimeEstimateSeconds(workerSlug?: string | null, mode?: string | null): number {
  if (!workerSlug) return 60;
  const estimate = WORKER_GENERATION_TIME_ESTIMATES[workerSlug];
  if (!estimate) return 60;
  if (mode && estimate.modes?.[mode] !== undefined) return estimate.modes[mode];
  return estimate.defaultSeconds;
}

export function formatGenerationTimeEstimate(seconds: number): string {
  if (seconds <= 45) return 'usually ready in under 1 minute';
  if (seconds <= 75) return 'usually ready in about 1 minute';
  if (seconds <= 120) return 'usually ready in under 2 minutes';
  if (seconds <= 180) return 'usually ready in 2-3 minutes';
  return 'usually ready in 3-4 minutes';
}

