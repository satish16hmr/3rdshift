export interface WorkerConfig {
  slug: string;
  name: string;
  personaName: string;
  emoji: string;
  category: string;
  categorySlug: string;
  description: string;
  taskType: 'light' | 'heavy';
  creditCost?: number;
  modeCredits?: Record<string, number>; // per-mode credit costs - overrides creditCost when present
  minPlan: 'starter' | 'pro' | 'operator';
  tags: string[];
  outputFormat: 'markdown' | 'csv' | 'json' | 'html' | 'images' | 'pptx' | 'clips' | 'captions';
  upworkPrice: string;
  active: boolean;
  deprecated?: boolean;     // true = slug is deprecated, use redirectTo for new destination
  redirectTo?: string;      // new slug to redirect this worker to (used with deprecated: true)
  iconBgClass?: string;
  catClass?: string;
  humanizeLevel?: 'light' | 'full'; // undefined = humanize disabled (non-text workers)
  chatCanGenerate?: boolean; // false = chat cannot trigger task generation (consultant-only workers). Default true for all.
  chainCompatible?: boolean; // false = cannot be added to Agent Mode chains (chat/file-only/no chain handler)
  hasTemplates?: boolean; // true = show WorkerTemplateCards above form
  templateGridCols?: string; // optional CSS grid-template-columns override (e.g. 'repeat(4, 1fr)' for 8-card layout)
  templates?: WorkerTemplate[];
  /**
   * subjectField — the form field name that identifies WHAT the deliverable is about.
   * This is the "identity" field: company name, product, client, topic, etc.
   * Used by Brand Context injection and test harness to distinguish operator identity
   * from task-specified subject. Each worker uses its own field name for this concept;
   * subjectField is the single documented source of truth.
   *
   * Examples:
   *   pricing-strategist: 'product'
   *   business-plan-writer: 'business_name'
   *   whitepaper-writer: 'topic'  (press-release-writer cut Brief 1C)
   *   case-study-writer: 'customer'
   *   proposal-writer: 'client_name'
   *
   * Workers that always operate on the operator's own business (Ava, Sam, Oscar, etc.)
   * do NOT need subjectField — their Brand Context identity is always the operator.
   */
  subjectField?: string;
  workerModes?: WorkerModeDefinition[]; // card-picker mode definitions for non-modeCredits workers (Heath, Quinn pattern)
  workerModesHeader?: string;   // header text for the card picker
  workerModesSubtitle?: string; // subtitle text for the card picker
  workerModeField?: string;     // which form field the card sets (e.g. 'mode', 'page_type')
  workerModesDefault?: string;  // which mode id is highlighted by default (defaults to first mode if unset)
  /**
   * handoffWorkers — workers shown in the "Keep going with your team" UI section
   * on the result page after this worker's output. NOT rendered in the output text.
   * For mode-gated workers, handoffs can be per-mode. Use the union of all modes if flat.
   */
  handoffWorkers?: HandoffWorkerDef[];
  handoffWorkersByMode?: Record<string, HandoffWorkerDef[]>; // keyed by mode id (workerModeField value)
  /**
   * maxOutputTokens — per-worker output cap passed directly to callAI max_tokens.
   * Overrides the WORKER_MAX_TOKENS entry in router.ts for this worker.
   * Used for cost guardrails on light workers that would otherwise produce long output.
   * Sourced from execute-task resolvedMaxTokens path via workerRegistryConfig.
   */
  maxOutputTokens?: number;
  generationTimeEstimateSeconds?: number;
  modeGenerationTimeEstimateSeconds?: Record<string, number>;
  /**
   * executionMode — controls how tasks/create dispatches this worker.
   * 'inngest': queued via Inngest (durable, handles long-running / external API workers)
   * 'direct': fire-and-forget fetch to execute-task (no queue delay, starts immediately)
   * Default: 'inngest' (safe default — only set 'direct' for pure Claude workers under ~40s typical)
   */
  executionMode?: 'inngest' | 'direct';
}

export interface HandoffWorkerDef {
  workerId: string;   // slug of the target worker
  cta: string;        // one-line CTA shown on the card
  mode?: string | null; // optional mode to prefill on the target worker's form
}

export interface WorkerTemplate {
  id: string;
  title: string;
  description: string;
  prefill: Record<string, unknown>;
  systemContextAddition?: string; // Appended to base system prompt when this template is selected
}

export interface WorkerModeDefinition {
  id: string;          // maps to the form field value
  icon: string;        // emoji
  title: string;
  spec: string;        // e.g. 'Full episode package / SEO-ready'
  useCase: string;     // business value sentence in callout box
  badge: 'free' | 'pro' | 'operator';
  credits: number | null;
  tierLine: string;    // e.g. 'Free · All plans'
  defaultTone?: string; // optional tone to prefill when this mode is selected (Quinn)
}

