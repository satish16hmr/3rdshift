function buildUserPrompt(i: Record<string, string>): string {
  const style = i.style || 'modern_short';
  const styleMap: Record<string, string> = {
    'Modern and short': 'modern_short',
    'Descriptive': 'descriptive',
    'Abstract': 'abstract',
    'Founder name-based': 'founder_name_based',
    'Mix of styles': 'mix_of_styles',
    'modern_short': 'modern_short',
    'descriptive': 'descriptive',
    'abstract': 'abstract',
    'founder_name_based': 'founder_name_based',
    'mix_of_styles': 'mix_of_styles',
  };
  const normalizedStyle = styleMap[style] || 'modern_short';
  const soundProfile = i.sound_profile || 'balanced';

  let prompt = `Generate product + brand names.

Business concept: ${i.concept || ''}`;

  if (i.industry) prompt += `\nIndustry: ${i.industry}`;
  if (i.target_audience) prompt += `\nTarget audience: ${i.target_audience}`;

  prompt += `\nNaming style: ${normalizedStyle}`;
  prompt += `\nSound profile: ${soundProfile}`;

  if (i.avoid) {
    prompt += `\nNames/words to avoid: ${i.avoid}`;
  } else {
    prompt += `\nNames/words to avoid: Default — avoid -ly suffix (2015-2019 dated), -ify overdone, Gen prefix, generic Tech/AI/Pro/Hub suffixes`;
  }

  // Field-swap detection
  const concept = i.concept || '';
  const industry = i.industry || '';
  const looksMismatched = (concept.length < 40 && (industry.length > 60)) ||
    /short|memorable|distinctive|modern|clean|minimalist/i.test(concept) && concept.length < 60;
  if (looksMismatched) {
    prompt += `\n\n[NOTE: Business concept input appears unusually brief or style-like. May be a field swap. Generate based on best inference and note this in output.]`;
  }

  prompt += `

REQUIREMENTS:
- 25 names across 3 tiers: Strongest (6-8) / Strong Contenders (8-10) / Worth Considering (8-10)
- Style: ${normalizedStyle} — ${normalizedStyle === 'modern_short' ? 'favor Invented/Neologism (15-18 names), 4-6 letter preferred, no -ly/-ify' : normalizedStyle === 'descriptive' ? 'favor Descriptive with modifiers (15-18 names), note trademark difficulty' : normalizedStyle === 'abstract' ? 'favor Suggestive using real words in unexpected contexts (15-18 names)' : normalizedStyle === 'founder_name_based' ? 'focus on founder-name variations — require founder name in concept field' : 'balanced mix of all 5 archetypes (5-6 each)'}
- Sound profile: ${soundProfile}
- Per Tier 1 name: archetype + rationale + sound profile note + domain notes + social handles + trademark risk
- Comparison Table (top 7 × Length / Syllables / Archetype / Trademark Risk / Global Friendly / Vibe / Sound Profile)
- Naming Rules Applied section
- Top 2-3 Final Recommendations with confidence + verification priority
- Verification Checklist with real URLs (USPTO TESS / EUIPO / WIPO / Namecheap / Namecheckr)
- Dated trend avoidance: no -ly, no -ify overdone, no Gen prefix, no generic Tech/AI/Pro suffixes`;

  return prompt;
}

export const productNamingSpecialistPrompt = {
  slug: 'product-naming-specialist',
  name: 'Naming Specialist',
  outputFormat: 'markdown' as const,
  systemPrompt: SULLY_SYSTEM,
  buildUserPrompt,
};
