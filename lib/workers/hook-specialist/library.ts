export function filterHooks(opts: {
  destination?: string;
  tone?: string;
  goal?: string;
  count?: number;
}): HookPattern[] {
  let filtered = HOOK_LIBRARY;
  if (opts.destination) {
    filtered = filtered.filter(
      (h) =>
        h.platforms.includes(opts.destination!) ||
        h.content_types.includes(opts.destination!)
    );
  }
  if (opts.tone) {
    filtered = filtered.filter((h) => h.tone_fit.includes(opts.tone!));
  }
  if (opts.goal) {
    filtered = filtered.filter((h) => h.goal_fit.includes(opts.goal!));
  }
  return filtered.slice(0, opts.count || 10);
}