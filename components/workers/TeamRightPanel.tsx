const TaskFormRightPanel = ({
  worker,
  workerSlug,
  slug,
  task,

  isSubmitting = false,
  completedTaskId = null,
  currentTask: propCurrentTask,
  currentTaskLoading = false,

  editorRef,
  editorInitialHtml,

  isEditorWorker,

  downloading,
  setDownloading,
  downloadOpen,
  setDownloadOpen,

  handleDownload,

  humanizing,
  humanizedText,
  handleHumanize,

  getEditorContent,
  getEditorHTML,

  showToast,

  onCreateNew,
  onAskRefine,
  showRefineInput,
  setShowRefineInput,
  onRefine,
  refineSubmitting: propRefineSubmitting,
}) => {
  const router = useRouter()
  const [editorHtml, setEditorHtml] = useState(editorInitialHtml || '')
  const [saving, setSaving] = useState(false)
  const [copied, setCopied] = useState(false)
  const [refineText, setRefineText] = useState('')
  const [retryingFree, setRetryingFree] = useState(false)
  const refineSubmitting = propRefineSubmitting
  const downloadRef = useRef(null)
  const takingLong = false
  const takingLongerThanUsual = false

  const handleFreeRetry = async () => {
    if (retryingFree || !(propCurrentTask || task)?.id) return
    setRetryingFree(true)
    await retryFreeTask({
      task: propCurrentTask || task,
      router,
      showToast,
    })
    setRetryingFree(false)
  }

  const selectedCategory = worker?.category || ''

  const currentTask = propCurrentTask || task

  const parsedOutput = (() => {
    if (!currentTask?.output) return null;
    let out = currentTask.output;
    if (typeof out === 'string') {
      try { out = JSON.parse(out); } catch { }
    }
    return out;
  })();

  const isImageTask = currentTask?.output_format === 'images' || parsedOutput?.format === 'images' || !!(currentTask?.worker_slug && currentTask.worker_slug.includes('image'))
  const isPptxTask = currentTask?.output_format === 'pptx' || parsedOutput?.format === 'pptx' || currentTask?.worker_slug === 'presentation-builder' || currentTask?.worker_slug === 'pitch-deck-writer'
  const isClipsTask = currentTask?.output_format === 'clips' || parsedOutput?.format === 'clips'
  const isCaptionsTask = currentTask?.output_format === 'captions' || parsedOutput?.format === 'captions'
  const isAudioTask = parsedOutput?.format === 'audio' || parsedOutput?.format === 'dubbing_pending'
  const isVideoTask = parsedOutput?.format === 'video' || parsedOutput?.format === 'video_pending'
  const isLeadsTask = currentTask?.output_format === 'leads' || Array.isArray(parsedOutput?.leads) || parsedOutput?.too_broad === true
  const isWebsiteTask = currentTask?.worker_slug === 'website-builder' || parsedOutput?.isWebsiteBuilder === true
  const isBrodyTask = currentTask?.worker_slug === 'kpi-dashboard-writer'
  const rawFailureMessage = String(
    parsedOutput?.error ||
    parsedOutput?.message ||
    currentTask?.error_message ||
    ''
  )
  const errMsg = rawFailureMessage
    .replace(/atlas cloud/gi, 'our video engine')
    .replace(/atlascloud/gi, 'our video engine')
    .replace(/seedance/gi, 'our video engine')
    .replace(/wan[\s-]?2\.?7?/gi, 'our video engine')
    .replace(/bytedance/gi, 'our video engine')
    .replace(/poll failed \(\d+\)/gi, 'generation failed')
    .trim()
  const isZeroLeadSearch = currentTask?.worker_slug === 'lead-generator' && /search returned no matches/i.test(errMsg)

  const images = parsedOutput?.images || []
  const hasAutoGeneratedImage = Array.isArray(images) && images.some(img => img?.source === 'auto_text_image')
  const hasRequestedTask = Boolean(completedTaskId)
  const loading = currentTaskLoading && hasRequestedTask && !currentTask

  const parsedMediaOutput = parsedOutput;

  const videoUrl = parsedMediaOutput?.url || parsedMediaOutput?.video_url || parsedMediaOutput?.videoUrl || (typeof parsedMediaOutput === 'string' && parsedMediaOutput.startsWith('http') ? parsedMediaOutput : '');
  const audioUrl = parsedMediaOutput?.url || parsedMediaOutput?.audio_url || parsedMediaOutput?.audioUrl || (typeof parsedMediaOutput === 'string' && parsedMediaOutput.startsWith('http') ? parsedMediaOutput : '');
  const audioPath = parsedMediaOutput?.audio_path || parsedMediaOutput?.audioPath || '';

  const imageOptions = (() => {
    if (Array.isArray(parsedMediaOutput)) return parsedMediaOutput;
    if (parsedMediaOutput?.images && Array.isArray(parsedMediaOutput.images)) return parsedMediaOutput.images;
    if (parsedMediaOutput?.urls && Array.isArray(parsedMediaOutput.urls)) return parsedMediaOutput.urls;
    if (parsedMediaOutput?.url || parsedMediaOutput?.image || parsedMediaOutput?.imageUrl) return [parsedMediaOutput];
    if (typeof parsedMediaOutput === 'string' && parsedMediaOutput.startsWith('http')) return [parsedMediaOutput];
    return [];
  })();

  const getMediaFormats = () => {
    if (isPptxTask) return ['pptx'];
    if (isClipsTask || isCaptionsTask) return []; // Handled by inline download buttons
    if (selectedCategory === 'Video' && videoUrl) return ['mp4'];
    if (selectedCategory === 'Audio & Voice' && (audioUrl || audioPath)) return ['mp3'];
    if (selectedCategory === 'Design & Creative' && imageOptions?.length > 0) return ['png'];
    return [];
  };

  const currentFormats = (() => {
    if (isPptxTask) return ['pptx'];
    if (isClipsTask || isCaptionsTask) return [];
    if (currentTask?.worker_slug === 'data-cleaner') {
      return getCadeDownloadFormats(currentTask?.input?.output_format);
    }
    if (currentTask?.worker_slug === 'customer-support-writer') {
      const agentTypes = ['Canned Responses', 'Complaint Responses', 'Refund Templates'];
      const raw = currentTask?.input?.content_type || '';
      const selected = Array.isArray(raw) ? raw : raw.split(',').map(s => s.trim()).filter(Boolean);
      const isAgentFacing = selected.some(t => agentTypes.includes(t));
      return isAgentFacing ? ['docx', 'pdf', 'csv'] : ['docx', 'pdf'];
    }
    const mediaFormats = getMediaFormats();
    if (mediaFormats.length > 0) return mediaFormats;
    return getDownloadFormats(currentTask?.worker_slug);
  })();

  const [imageDownloading, setImageDownloading] = useState({})

  const handleDownloadImage = async (url: string, index: number) => {
    setImageDownloading(prev => ({ ...prev, [index]: true }))
    try {
      const res = await fetch(url)
      const blob = await res.blob()
      const a = document.createElement('a')
      a.href = URL.createObjectURL(blob)
      a.download = `${currentTask?.worker_slug || 'image'}-concept-${index + 1}.png`
      a.click()
      URL.revokeObjectURL(a.href)
    } catch {
      window.open(url, '_blank')
    } finally {
      setImageDownloading(prev => ({ ...prev, [index]: false }))
    }
  }

  const localHandleDownload = (fmt) => {
    if (fmt === 'pptx' && parsedOutput?.downloadUrl) {
      const a = document.createElement('a'); a.href = parsedOutput.downloadUrl; a.download = parsedOutput.fileName || 'presentation.pptx'; a.target = '_blank'; a.click(); return;
    }
    if (fmt === 'mp4' && videoUrl) {
      const a = document.createElement('a'); a.href = videoUrl; a.download = 'video.mp4'; a.target = '_blank'; a.click(); return;
    }
    if (fmt === 'mp3' && audioUrl) {
      const a = document.createElement('a'); a.href = audioUrl; a.download = 'audio.mp3'; a.target = '_blank'; a.click(); return;
    }
    if (fmt === 'png' && imageOptions?.length > 0) {
      imageOptions.forEach((opt, i) => {
        const src = typeof opt === 'string' ? opt : (opt?.url || opt?.image || opt?.imageUrl || opt?.src);
        if (src) { handleDownloadImage(src, i); }
      });
      return;
    }
    handleDownload(fmt);
  }


  const isHumanizable = [
    'blog-post-writer',
    'email-writer',
    'social-media-post-writer',
    'ad-copy-writer',
    'product-description-writer'
  ].includes(currentTask?.worker_slug)
  const [refining, _setRefining] = useState(false)
  const setRefining = (v) => _setRefining(v)
  const [brandKitLoading, setBrandKitLoading] = useState({})
  const [shayRefineOpen, setShayRefineOpen] = useState(null)
  const [shayRefineLoading, setShayRefineLoading] = useState({})
  const [previewImage, setPreviewImage] = useState(null)
  const [show, setShow] = useState(false)
  const [previewLoading, setPreviewLoading] = useState(true)
  const [failedImages, setFailedImages] = useState<Record<number, boolean>>({})

  const openPreview = useCallback((src) => {
    setPreviewImage(src)
    setPreviewLoading(true)
    requestAnimationFrame(() => requestAnimationFrame(() => setShow(true)))
  }, [])

  const closePreview = useCallback((e) => {
    e?.stopPropagation?.()
    setShow(false)
    setTimeout(() => setPreviewImage(null), 200)
  }, [])

  const handleShayRefine = async (url, index, refineType) => {
    setShayRefineOpen(null)
    const loadingKey = `${index}:${refineType}`
    setShayRefineLoading(prev => ({ ...prev, [loadingKey]: true }))
    try {
      const recolorColors = refineType === 'refine_recolor'
        ? window.prompt('Optional: enter colors to try (hex codes or names). Leave blank for 3 color directions.', '')
        : ''
      if (recolorColors === null) {
        setShayRefineLoading(prev => ({ ...prev, [loadingKey]: false }))
        return
      }
      const supabase = createClient()
      const { data: { session } } = await supabase.auth.getSession()
      const sourceInput = currentTask?.input || {}
      const res = await fetch('/api/tasks/create', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'Authorization': `Bearer ${session?.access_token}` },
        body: JSON.stringify({
          worker_slug: 'logo-concept-generator',
          workspace_id: currentTask?.workspace_id,
          input: {
            ...sourceInput,
            shay_mode: refineType,
            brand_name: parsedMediaOutput?.brandName || sourceInput.brand_name || 'Logo',
            industry: sourceInput.industry || 'Brand',
            style: sourceInput.style || 'Professional',
            colors: sourceInput.colors || recolorColors || 'Use the selected concept palette',
            selected_concept_url: url,
            source_task_id: currentTask?.id,
            source_image_index: index,
            concept_number: String(index + 1),
            recolor_colors: recolorColors || '',
            refinement_instruction: refineType === 'refine_more_like_this'
              ? 'Create three minor variations of the selected logo. Preserve the same icon DNA, wordmark, layout, and composition.'
              : refineType === 'refine_recolor'
                ? (recolorColors ? `Recolor using: ${recolorColors}` : 'Generate three distinct color directions.')
                : 'Extract one clean icon/mark-only submark from the selected logo and remove the wordmark.',
          },
        }),
      })
      const data = await res.json()
      if (!res.ok || !data.taskId) throw new Error(data.error || 'Refine failed')
      router.push(`/dashboard/tasks/result?taskId=${data.taskId}`)
    } catch (e) {
      alert(`Refine failed: ${e instanceof Error ? e.message : 'please try again.'}`)
      setShayRefineLoading(prev => ({ ...prev, [loadingKey]: false }))
    }
  }

  const renderShayRefineControls = (url, i) => {
    const options = [
      { id: 'refine_more_like_this', label: 'More like this', detail: '3 variations' },
      { id: 'refine_recolor', label: 'Recolor', detail: 'up to 3 recolors' },
      { id: 'refine_submark', label: 'Submark / icon only', detail: '1 icon' },
    ]
    return (
      <Dropdown>
        <DropdownButton
          as="button"
          className="rounded-lg border border-blue-200 bg-blue-50 px-3 py-1.5 text-xs font-semibold text-blue-700 transition hover:bg-blue-100 cursor-pointer outline-none!"
        >
          Refine this → <span className="font-medium text-blue-500">1 credit</span>
        </DropdownButton>
        <DropdownMenu anchor="bottom end" className="w-64! space-y-1 p-2 border border-zinc-200 bg-zinc-50 shadow-lg">
          {options.map(option => {
            const loadingKey = `${i}:${option.id}`
            return (
              <DropdownItem
                key={option.id}
                onClick={() => handleShayRefine(url, i, option.id)}
                disabled={!!shayRefineLoading[loadingKey]}
                className="flex! items-center! justify-between! rounded-md! bg-white! px-3! py-2! text-left! text-xs! text-zinc-700! shadow-sm! transition! hover:bg-zinc-100! disabled:opacity-60! cursor-pointer!"
              >
                <DropdownLabel className="font-semibold! text-xs! text-zinc-950!">{option.label}</DropdownLabel>
                <DropdownDescription className="text-zinc-400!">{shayRefineLoading[loadingKey] ? 'Starting…' : option.detail}</DropdownDescription>
              </DropdownItem>
            )
          })}
        </DropdownMenu>
      </Dropdown>
    )
  }

  const handleBrandKit = async (url, index, brandName, taskId) => {
    setBrandKitLoading(prev => ({ ...prev, [index]: true }))
    try {
      const { createClient } = await import('@/lib/supabase/client')
      const supabase = createClient()
      const { data: { session } } = await supabase.auth.getSession()
      const res = await fetch('/api/shay/brand-kit', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'Authorization': `Bearer ${session?.access_token}` },
        body: JSON.stringify({ imageUrl: url, brandName: brandName || 'logo', conceptIndex: index + 1, taskId, imageIndex: index }),
      })
      const data = await res.json()
      if (data.downloadUrl) {
        const a = document.createElement('a')
        a.href = data.downloadUrl
        a.download = data.fileName || `brand-kit-concept-${index + 1}.zip`
        a.click()
        if (data.vectorizationFailed) {
          alert('Your brand kit is downloading! Note: Vector files (SVG, EPS, PDF) are still processing. Click “Download Brand Kit” again in a minute to get the full kit with vector files.')
        }
      } else {
        alert(`Brand kit failed: ${data.error || 'unknown error'}`)
      }
    } catch (e) {
      alert(`Brand kit generation failed: ${e instanceof Error ? e.message : 'please try again.'}`)
    }
    setBrandKitLoading(prev => ({ ...prev, [index]: false }))
  }

  const parseOutputText = (output) => {
    if (!output) return ''
    let text = ''
    if (typeof output === 'string') {
      try {
        const parsed = JSON.parse(output)
        text = parsed?.text || (typeof parsed === 'string' ? parsed : '')
      } catch {
        text = output
      }
    } else {
      text = output?.text || (typeof output === 'string' ? output : '')
    }

    if (!text) return ''

    try {
      const rawHtml = marked.parse(text, { breaks: true, gfm: true })
      return typeof window !== 'undefined' ? DOMPurify.sanitize(rawHtml) : rawHtml
    } catch (e) {
      console.error('Markdown parse failed', e)
      return text
    }
  }

  const handleEditorUpdate = useCallback((html: string) => {
    setEditorHtml(html)
  }, [])

  const handleCopy = async () => {
    let success = false
    if (isEditorWorker && editorRef?.current) {
      const html = editorRef.current.getHTML()
      const plain = editorRef.current.getText()

      try {
        if (typeof ClipboardItem !== 'undefined') {
          await navigator.clipboard.write([
            new ClipboardItem({
              'text/html': new Blob([html || ''], { type: 'text/html' }),
              'text/plain': new Blob([plain || ''], { type: 'text/plain' }),
            }),
          ])
          showToast?.('Copied to clipboard')
          success = true
        }
      } catch (err) {
        console.error('Clipboard rich copy failed', err)
      }

      if (!success && plain) {
        navigator.clipboard.writeText(plain)
        showToast?.('Copied to clipboard')
        success = true
      }
    } else if (getEditorContent) {
      navigator.clipboard.writeText(getEditorContent())
      showToast?.('Copied to clipboard')
      success = true
    }

    if (success) {
      setCopied(true)
      setTimeout(() => setCopied(false), 3000)
    }
  }

  const handleSave = async () => {
    if (!currentTask?.id) return
    setSaving(true)
    try {
      const supabase = createClient()
      const { data: { session } } = await supabase.auth.getSession()
      if (!session) {
        showToast?.('Please login to save')
        return
      }

      const res = await fetch('/api/tasks/save-edit', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${session.access_token}`
        },
        body: JSON.stringify({
          taskId: currentTask.id,
          edited_output: editorHtml
        })
      })

      if (!res.ok) {
        const err = await res.json().catch(() => ({}))
        throw new Error(err.error || 'Failed to save')
      }

      showToast?.('Saved successfully')
    } catch (err: any) {
      showToast?.(err.message || 'Error saving task')
    } finally {
      setSaving(false)
    }
  }

  // Show "No task" only if neither a task object nor a completedTaskId are provided
  // if (!task && !completedTaskId) {
  //   return <div>No task</div>
  // }

  const workerName = worker?.name || slug
  const workerPersona = worker?.personaName || workerName.split(' ')[0]
  const isGenerating = isSubmitting || (!!currentTask && ['processing', 'pending', 'queued'].includes(currentTask.status)) || (!!completedTaskId && (!currentTask || !['completed', 'failed'].includes(currentTask.status)))

  return (
    <div
      className={`bg-no-repeat bg-cover p-4! sm:p-6! h-full max-h-[calc(100vh-60px)] 2xl:max-h-[calc(100vh-85px)] overflow-x-hidden 2xl:flex 2xl:justify-center ${(completedTaskId && currentTask) ? "p-0 bg-none overflow-y-hidden" : "overflow-y-auto"}`}
      style={{ backgroundImage: `url(${AuthBgPng.src})` }}
    >
      {/* Outer Gradient Wrapper */}
      <div className={`rounded-3xl bg-white/95 backdrop-blur-md border border-zinc-200 overflow-x-hidden ${(completedTaskId && currentTask) ? "border-0 max-h-[800px] 2xl:max-h-[600px] h-full overflow-hidden my-auto" : "h-fit 2xl:my-auto"} shadow-lg space-y-5 w-full`}>

        {/* Loading State */}
        {loading && !isGenerating ? (
          <div className='p-4 sm:p-6 h-full space-y-5'>
            {/* About */}
            <div className="rounded-xl border border-zinc-200 bg-white p-4 sm:p-6">
              <Skeleton className="h-5 w-48 mb-3" />
              <Skeleton className="h-4 w-full" />
              <Skeleton className="h-4 w-5/6 mt-1.5" />
              <Skeleton className="h-4 w-4/5 mt-1.5" />
            </div>

            {/* Brand Context */}
            <div className="rounded-xl border border-zinc-200 bg-white p-4 sm:p-6">
              <Skeleton className="h-5 w-36 mb-3" />
              <Skeleton className="h-4 w-64 mb-1.5" />
              <Skeleton className="h-4 w-72" />
            </div>

            {/* Previous Tasks */}
            <div className="rounded-xl border border-zinc-200 bg-white p-4 sm:p-6">
              <Skeleton className="h-5 w-32 mb-3" />
              <Skeleton className="h-4 w-28" />
            </div>
          </div>
        ) : isGenerating ? (
          <div className="flex flex-col h-[600px] bg-white rounded-3xl overflow-hidden">
            <div className='bg-zinc-50 py-3 px-4 sm:px-6 border-b border-zinc-200'>
              <p className='text-zinc-950 text-sm'>Generating...</p>
              <p className='text-zinc-500 text-base'>wait 60-80 seconds</p>
            </div>
            <div className='flex items-center justify-center gap-3 flex-1 px-4 sm:px-6'>
              <div className='size-[34px] border border-zinc-200 rounded-lg flex items-center justify-center'>1</div>
              <div>
                <p className='text-zinc-900 text-sm font-medium'>{workerPersona} doing your task...</p>
                <p className='text-zinc-600 text-xs mt-1'>Generating your result now.</p>
              </div>
            </div>
          </div>
        ) : completedTaskId && currentTask ? (
          <div className="relative flex flex-col h-full rounded-3xl">
            <div className="flex xl:flex-wrap lg:items-center justify-between gap-4 bg-[#FAFAFA] border-b border-[#E9EAEB] p-4 sm:px-6 sm:py-3 sm:py-4">
              <div className="flex items-center gap-2 min-[390px]:gap-3 min-w-0">
                {currentTask?.worker_slug && getWorkerAvatarSrcBySlug(currentTask.worker_slug) && (
                  <Image
                    src={getWorkerAvatarSrcBySlug(currentTask.worker_slug)}
                    width={48}
                    height={48}
                    alt="avatar"
                    className="rounded-full border border-zinc-200 object-cover shrink-0 xl:hidden"
                  />
                )}
                <div className="min-w-0">
                  <Heading className="text-base! font-regular! text-zinc-950! truncate max-w-full lg:max-w-100">
                    {worker?.personaName ? `${worker.personaName} · ${worker.name}` : (worker?.name || currentTask?.worker_slug)}
                  </Heading>
                  <div className="mt-1 flex items-center gap-1.5 flex-wrap">
                    <Badge
                      color={
                        currentTask?.status === 'completed'
                          ? (currentTask?.output_status === 'potentially_truncated' ? 'yellow' : 'green')
                          : currentTask?.status === 'failed'
                            ? 'red'
                            : 'yellow'
                      }
                    >
                      {currentTask?.status === 'completed'
                        ? (currentTask?.output_status === 'potentially_truncated' ? 'Partial' : 'Completed')
                        : currentTask?.status === 'failed'
                          ? 'Failed'
                          : takingLong
                            ? 'Still running'
                            : takingLongerThanUsual
                              ? 'Taking longer than usual'
                              : 'Estimated time'}
                    </Badge>
                  </div>
                </div>
              </div>
              <div className='flex ms-auto sm:ms-0 gap-3'>
                {!isImageTask && !isVideoTask && !isAudioTask && currentTask?.status !== 'failed' && (
                  <Button
                    variant='outline'
                    className="hidden xl:flex"
                    onClick={handleSave}
                    disabled={saving || !currentTask?.id}
                  >
                    {saving ? (
                      <div className="size-4 animate-spin rounded-full border-2 border-zinc-300 border-t-zinc-800" />
                    ) : (
                      <Save className="size-4" />
                    )}
                  </Button>
                )}
                {/* Top bar — PRIMARY actions only: Copy + Download (text) or Download equiv for others */}
                {currentTask?.status === 'completed' && (
                  <>
                    <div className="items-center gap-2 sm:gap-2 flex-wrap hidden xl:flex">

                      {/* Copy — text workers only (not audio, not video, not leads, not website) */}
                      {!isImageTask && !isClipsTask && !isCaptionsTask && !isPptxTask && !isAudioTask && !isVideoTask && !isLeadsTask && !isWebsiteTask && (
                        <Button
                          variant="outline"
                          className="w-11! h-9! flex! items-center! justify-center!"
                          onClick={handleCopy}
                        >
                          {copied ? <Check className="size-4 text-green-600" /> : <Copy className="size-4" />}
                        </Button>
                      )}

                      {/* Download — generic formats support (text, images, media) */}
                      {!isImageTask && !isClipsTask && !isCaptionsTask && !isPptxTask && !isAudioTask && !isLeadsTask && !isWebsiteTask && (
                        <DownloadDropdown
                          content={isEditorWorker
                            ? (getEditorHTML() || currentTask?.output?.text || '')
                            : (currentTask?.output?.text) || ''
                          }
                          slug={currentTask?.worker_slug || ''}
                          taskId={currentTask?.id || ''}
                          settings={currentTask?.input || {}}
                          taskOutput={currentTask?.output}
                          variant="button"
                          align="right"
                          onDownloadingChange={setDownloading}
                        />
                      )}

                      {/* Secondary actions row — Chat, Save to Google, Humanize */}
                      {currentTask?.status === 'completed' && (
                        <>
                          <Button variant="outline" href={`/dashboard/team/${currentTask?.worker_slug}?tab=chat&taskId=${currentTask.id}`}>
                            💬 Chat with {worker?.personaName || worker?.name?.split(' ')[0] || 'them'}
                          </Button>
                          {currentTask?.worker_slug === 'resume-writer' && (
                            <Button variant="outline" href="/dashboard/team/resume-writer">
                              ✉️ Write cover letter with Beck
                            </Button>
                          )}
                          {currentTask?.worker_slug === 'cover-letter-writer' && (
                            <Button variant="outline" href="/dashboard/team/resume-writer">
                              📄 Write resume with Beck
                            </Button>
                          )}
                          {!isWebsiteTask && currentTask?.id && (
                            <SendToDropdown
                              taskId={currentTask.id}
                              workerSlug={currentTask.worker_slug}
                              title={((['topic', 'subject', 'title', 'keyword', 'company_name', 'product_name', 'task_description', 'task_input'].map(k => currentTask?.input?.[k]).find(v => typeof v === 'string' && v?.length > 3) || Object.values(currentTask?.input || {}).find(v => typeof v === 'string' && v?.length > 3))?.slice?.(0, 60))}
                            />
                          )}

                          {/* Image worker: Refine variation in secondary row */}
                          {isImageTask && currentTask?.worker_slug !== 'logo-concept-generator' && (
                            <Button variant="outline" onClick={async () => {
                              if (refining) return
                              setRefining(true)
                              try {
                                const supabase = createClient()
                                const { data: { session } } = await supabase.auth.getSession()
                                if (!session) return
                                // D1 fix: use /api/tasks/refine for variation too
                                const varRes = await fetch('/api/tasks/refine', {
                                  method: 'POST',
                                  headers: { 'Content-Type': 'application/json', 'Authorization': `Bearer ${session.access_token}` },
                                  body: JSON.stringify({
                                    original_task_id: currentTask.id,
                                    refine_input: { ...(currentTask?.input || {}), _refine_variation: true },
                                  }),
                                })
                                if (!varRes.ok) { setRefining(false); return }
                                const varData = await varRes.json()
                                router.push(`/dashboard/tasks/result?taskId=${varData.taskId}`)
                              } catch { setRefining(false) }
                            }}>
                              {refining ? 'Refining…' : '🔄 Refine'}
                            </Button>
                          )}
                        </>
                      )}

                      {/* Image workers: Generate More is the primary action */}
                      {isImageTask && currentTask?.worker_slug !== 'logo-concept-generator' && (
                        <Button variant="primary" href={`/dashboard/team/${currentTask?.worker_slug}`}>Generate More →</Button>
                      )}
                      {isClipsTask && (
                        <Button variant="primary" href={`/dashboard/team/${currentTask?.worker_slug}`}>Extract More →</Button>
                      )}
                      {isCaptionsTask && (
                        <Button variant="primary" href={`/dashboard/team/${currentTask?.worker_slug}`}>Generate More →</Button>
                      )}
                    </div>
                    <div className="">
                      <MobileActionsDropdown
                        task={currentTask}
                        worker={worker}
                        isImageTask={isImageTask}
                        isClipsTask={isClipsTask}
                        isCaptionsTask={isCaptionsTask}
                        isPptxTask={isPptxTask}
                        isAudioTask={isAudioTask}
                        isVideoTask={isVideoTask}
                        isLeadsTask={isLeadsTask}
                        isWebsiteTask={isWebsiteTask}
                        isEditorWorker={isEditorWorker}
                        editorRef={editorRef}
                        getEditorContent={getEditorContent}
                        getEditorHTML={getEditorHTML}
                        showToast={showToast}
                        isHumanizable={isHumanizable}
                        humanizing={humanizing}
                        humanizedText={humanizedText}
                        handleHumanize={handleHumanize}
                        refining={refining}
                        setRefining={setRefining}
                        setDownloading={setDownloading}
                        handleSave={handleSave}
                        saving={saving}
                        currentTask={currentTask}
                      />
                    </div>
                  </>
                )}
              </div>
            </div>
            <div className={`min-h-0 flex-1 overflow-y-auto overflow-x-hidden p-4 sm:p-6 [scrollbar-gutter:stable] ${showRefineInput ? 'pb-48 sm:pb-40' : ''}`}>
              {
                currentTask?.status === 'failed' ? (
                  <div className="flex-1 flex flex-col items-center justify-center">
                    <Image src="/images/my-tasks/emptyTasks.png" alt="Task failed" width={162} height={116} />
                    <Text className="text-xl! font-semibold! text-zinc-800! mb-3 -mt-6">
                      {isZeroLeadSearch ? 'No matching leads found' : 'Task failed'}
                    </Text>
                    <Text className="text-sm text-zinc-400 text-center">
                      {isZeroLeadSearch
                        ? 'Try broadening your criteria — use a wider location, additional job titles, or a broader company size range.'
                        : "Something went wrong on our end — you weren't charged. Try again."}
                    </Text>
                    {errMsg && <Text className="mt-2 max-w-xl text-center text-xs text-zinc-400">{errMsg}</Text>}
                    <Button variant="outline" className="mt-5" href={`/dashboard/team/${worker?.worker_slug}?retryTaskId=${currentTask?.id}`}>Try again →</Button>
                    <div className="rounded-xl border border-zinc-200 bg-white p-4 sm:p-6 shadow-sm hover:shadow-md transition-all w-full mt-6">
                      <Subheading className="text-lg font-semibold text-zinc-800">
                        Previous Tasks
                      </Subheading>
                      <div className="mt-3">
                        <Link
                          href="/dashboard/tasks"
                          className="text-sm text-zinc-500 hover:text-blue-600 underline transition-colors"
                        >
                          View all tasks →
                        </Link>
                      </div>
                    </div>
                  </div>
                ) : (
                  <>
                    {/* Truncation warning banner */}
                    {currentTask?.status === 'completed' && currentTask?.output_status === 'potentially_truncated' && (
                      <div className="pb-4">
                        <div className="flex flex-col sm:flex-row items-start gap-3 rounded-xl border border-amber-200 bg-amber-50 px-4 sm:px-5 py-4">
                          <span className="text-lg shrink-0">⚠️</span>
                          <div className="flex-1">
                            <p className="text-sm font-semibold text-amber-900">This output may be incomplete</p>
                            <p className="mt-0.5 text-xs sm:text-[13px] text-amber-800">The generation was cut short. You can retry for free — no credits will be charged.</p>
                          </div>
                          <button
                            onClick={handleFreeRetry}
                            disabled={retryingFree}
                            className="shrink-0 flex items-center gap-1.5 rounded-lg bg-amber-600 px-3 py-1.5 text-xs font-semibold text-white transition hover:bg-amber-700 disabled:opacity-50 cursor-pointer"
                          >
                            {retryingFree ? (
                              <>
                                <Loader size={3.5} className="!size-3.5" />
                                <span>Retrying…</span>
                              </>
                            ) : (
                              'Retry for free'
                            )}
                          </button>
                        </div>
                      </div>
                    )}
                    {(() => {
                      if (isPptxTask) return <PptxOutput output={parsedOutput} />;
                      if (isClipsTask) return <ClipsOutput output={parsedOutput} />;
                      if (isCaptionsTask) return <CaptionsOutput output={parsedOutput} />;
                      if (isWebsiteTask) return <WebsiteBuilderOutput task={currentTask} isPanel={true} />;
                      if (isLeadsTask) return <LeadCards output={parsedOutput} taskId={currentTask?.id} task={currentTask} />;
                      if (isBrodyTask) {
                        return (
                          <BrodyOutput
                            output={currentTask?.output}
                            metricData={currentTask?.output?.metricData}
                            editorRef={editorRef}
                            onUpdate={handleEditorUpdate}
                            isEditable={true}
                          />
                        );
                      }

                      if (selectedCategory === 'Video') {
                        if (!videoUrl) return <div className="flex justify-center items-center h-full text-zinc-500">Generating video...</div>;
                        return (
                          <>
                            <div className="w-full flex justify-center py-6 px-4 pb-12 overflow-y-auto">
                              <VideoPlayer
                                videoUrl={videoUrl}
                                fileName={currentTask?.output?.video_filename || 'video.mp4'}
                                label={currentTask?.output?.video_filename?.replace(/-[a-z0-9-]+\.mp4$/, '').replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase()) || 'Video'}
                                className='w-full! min-[1790px]:w-[80%]!'
                              />
                            </div>
                            <div className='flex xl:hidden mt-4 w-full'>
                              {!isSubmitting && currentTask?.status === 'completed' && worker && (
                                <HandoffCards
                                  worker={worker}
                                  taskInput={currentTask.input || {}}
                                  taskOutput={currentTask.output || {}}
                                />
                              )}
                            </div>
                          </>
                        );
                      } else if (selectedCategory === 'Audio & Voice') {
                        if (!audioUrl && !audioPath) return <div className="flex justify-center items-center h-full text-zinc-500">Generating audio...</div>;
                        return (
                          <AudioPlayer
                            audioUrl={audioUrl}
                            audioPath={audioPath}
                            taskId={currentTask?.id}
                            fileName="audio.mp3"
                            label="Audio upload"
                          />
                        );
                      } else if (selectedCategory === 'Design & Creative' && isImageTask) {
                        if (!imageOptions || imageOptions.length === 0) {
                          return <div className="flex justify-center items-center h-full text-zinc-500">Generating design...</div>;
                        }
                        return (
                          <div className="space-y-6">
                            {/* 48h notice */}
                            <div className="flex flex-wrap items-center gap-2 sm:gap-3 rounded-xl border border-amber-200 bg-amber-50 px-3.5 sm:px-5 py-2 sm:py-3.5">
                              <span className="text-lg">⏱️</span>
                              <p className="text-amber-800 text-sm">
                                <span className="font-semibold">Download within 48 hours.</span> Images expire 48 hours after generation.
                              </p>
                            </div>

                            <div className={`grid grid-cols-1 ${currentTask?.worker_slug === 'logo-concept-generator' ? 'gap-3 sm:grid-cols-2' : 'gap-2.5 sm:grid-cols-2'}`}>
                              {imageOptions.map((option, i) => {
                                const src = typeof option === 'string' ? option : (option?.url || option?.image || option?.imageUrl || option?.src);
                                if (!src) return null;
                                const label = option?.label || (currentTask?.worker_slug === 'logo-concept-generator' ? `Concept ${i + 1}` : `Option ${i + 1}`);
                                return (
                                  <div
                                    key={i}
                                    className={`bg-white rounded-xl border border-zinc-200 ${currentTask?.worker_slug === 'logo-concept-generator' ? 'overflow-visible' : 'overflow-hidden'}`}
                                  >
                                    {failedImages[i] ? (
                                      <div className={`w-full flex flex-col items-center justify-center bg-zinc-50 p-4 text-center ${currentTask?.worker_slug === 'logo-concept-generator' ? 'h-24 rounded-t-xl' : 'h-32'}`}>
                                        <span className="text-xl mb-1">🖼️</span>
                                        <p className="text-xs font-medium text-zinc-600">Image expired or unavailable</p>
                                      </div>
                                    ) : (
                                      <img
                                        src={src}
                                        alt={`designer-output-${i}`}
                                        onError={() => setFailedImages(prev => ({ ...prev, [i]: true }))}
                                        className={`w-full cursor-pointer transition-opacity hover:opacity-90 ${currentTask?.worker_slug === 'logo-concept-generator' ? 'h-24 rounded-t-xl bg-white object-contain' : 'h-32 object-cover'}`}
                                        onClick={(e) => {
                                          if (failedImages[i]) return
                                          e.stopPropagation()
                                          openPreview(src)
                                        }}
                                      />
                                    )}
                                    <div className={`${currentTask?.worker_slug === 'logo-concept-generator' ? 'px-3 py-2' : 'px-4 py-3'} border-t border-zinc-950/[0.06] space-y-2`}>
                                      {currentTask?.worker_slug === 'logo-concept-generator' ? (
                                        <>
                                          <div className="flex flex-wrap items-center justify-between gap-2">
                                            <Text className="text-xs text-zinc-400 font-medium">{label}</Text>
                                            <div className="flex flex-wrap justify-end gap-2">
                                              <button
                                                onClick={() => handleBrandKit(src, i, parsedMediaOutput?.brandName, currentTask?.id)}
                                                disabled={!!brandKitLoading[i]}
                                                className="flex items-center gap-1.5 rounded-lg bg-blue-600 px-3 py-1.5 text-xs font-semibold text-white transition hover:bg-blue-700 disabled:opacity-60"
                                              >
                                                {brandKitLoading[i] ? (
                                                  <><span className="size-3 animate-spin rounded-full border border-white border-t-transparent" /> Generating...</>
                                                ) : (
                                                  <>
                                                    <svg width="12" height="12" viewBox="0 0 12 12" fill="none">
                                                      <path d="M6 1.5v6m0 0L4 5.5m2 2l2-2M2 9.5v.5a.5.5 0 00.5.5h7a.5.5 0 00.5-.5V9.5" stroke="currentColor" strokeWidth="1.25" strokeLinecap="round" strokeLinejoin="round" />
                                                    </svg>
                                                    Download Brand Kit →
                                                  </>
                                                )}
                                              </button>
                                              {renderShayRefineControls(src, i)}
                                            </div>
                                          </div>
                                          <div className="flex justify-end">
                                            <button
                                              onClick={() => handleDownloadImage(src, i)}
                                              disabled={!!imageDownloading[i]}
                                              className="text-[11px] text-zinc-400 hover:text-zinc-600 transition-colors disabled:opacity-60 flex items-center gap-1 cursor-pointer"
                                            >
                                              {imageDownloading[i] ? (
                                                <>
                                                  <Loader size={3} className="!size-3" />
                                                  Downloading…
                                                </>
                                              ) : (
                                                'or download PNG only'
                                              )}
                                            </button>
                                          </div>
                                        </>
                                      ) : (
                                        <div className="flex items-center justify-between">
                                          <span className="text-sm text-zinc-800">{label}</span>
                                          <button
                                            onClick={() => handleDownloadImage(src, i)}
                                            disabled={!!imageDownloading[i]}
                                            className="flex items-center gap-1.5 rounded-lg bg-zinc-900 px-3 py-1.5 text-xs font-semibold text-white transition hover:bg-zinc-700 cursor-pointer disabled:opacity-60"
                                          >
                                            {imageDownloading[i] ? (
                                              <>
                                                <Loader size={3.5} className="!size-3.5" />
                                                Downloading…
                                              </>
                                            ) : (
                                              <>
                                                <svg width="12" height="12" viewBox="0 0 12 12" fill="none">
                                                  <path d="M6 1.5v6m0 0L4 5.5m2 2l2-2M2 9.5v.5a.5.5 0 00.5.5h7a.5.5 0 00.5-.5V9.5" stroke="currentColor" strokeWidth="1.25" strokeLinecap="round" strokeLinejoin="round" />
                                                </svg>
                                                PNG
                                              </>
                                            )}
                                          </button>
                                        </div>
                                      )}
                                    </div>
                                  </div>
                                );
                              })}
                            </div>
                          </div>
                        );
                      } else {
                        return (
                          <>
                            {hasAutoGeneratedImage && (
                              <AutoGeneratedImageOutput output={currentTask?.output} workerSlug={currentTask?.worker_slug} />
                            )}
                            <TiptapEditor
                              ref={editorRef}
                              initialHtml={
                                parseOutputText(currentTask?.output) ||
                                editorInitialHtml
                              }
                              onUpdate={handleEditorUpdate}
                              autoSaveMs={30000}
                            />
                          </>
                        );
                      }
                    })()}
                  </>
                )
              }
            </div>
            {
              currentTask?.status !== 'failed' && (
                <div className="bg-zinc-50 py-5 px-6 border-t border-zinc-200 flex flex-wrap items-center justify-between sticky left-0 bottom-0 z-10">
                  <div
                    className={`px-6 pt-4 pb-3 border-b border-zinc-200 absolute w-full bg-white z-30 bottom-full left-0 transition-all duration-300 ease-out ${showRefineInput
                      ? 'translate-y-0 opacity-100 pointer-events-auto'
                      : 'translate-y-full opacity-0 pointer-events-none'
                      }`}
                  >
                    <div className="flex flex-col gap-2 justify-start">
                      <textarea
                        value={refineText}
                        onChange={e => setRefineText(e.target.value)}
                        placeholder="e.g. Make it shorter, change the tone to casual..."
                        rows={3}
                        className="flex-1 text-sm rounded-lg border border-zinc-200 px-3 py-2 resize-none focus:outline-none focus:ring-2 focus:ring-blue-500 focus:border-transparent"
                      />
                      <div className='flex items-center gap-2 justify-start'>
                        <Button
                          variant='outline'
                          type="button"
                          onClick={async () => {
                            await onRefine?.(refineText)
                            setRefineText('')
                          }}
                          disabled={refineSubmitting || !refineText.trim()}
                          className="bg-white"
                        >
                          {refineSubmitting ? (
                            <div className="size-4 animate-spin rounded-full border-2 border-zinc-300 border-t-zinc-800" />
                          ) : (
                            'Refine'
                          )}
                        </Button>
                        <Button
                          variant='outline'
                          onClick={() => {
                            setShowRefineInput(false)
                            setRefineText('')
                          }}
                          disabled={refineSubmitting}
                          className="bg-white"
                        >
                          Cancel
                        </Button>
                      </div>
                    </div>
                  </div>
                  <WorkerRating
                    currentTask={currentTask}
                    showToast={showToast}
                    className="w-full"
                  />

                </div>
              )
            }
          </div>

        ) : (
          <div className='p-4 sm:p-6 h-full space-y-5'>
            {/* About */}
            <div className="rounded-xl border border-zinc-200 bg-white p-4 sm:p-6 hover:shadow-md transition-all">
              <Subheading className="text-lg font-semibold text-zinc-800">
                About this team member
              </Subheading>
              <Text className="mt-3 text-zinc-600 leading-relaxed">
                {worker?.description || `${workerName} is ready to work.`}
              </Text>
            </div>

            {/* Example Output */}
            {worker?.catClass === 'wc-vi' && slug === 'ad-creative-generator' && (
              <div className="rounded-xl border border-zinc-200 bg-white p-4 sm:p-6 hover:shadow-md transition-all">
                <Subheading className="text-lg font-semibold text-zinc-800">
                  Example Output
                </Subheading>
                <div className="mt-3 space-y-2">
                  <Link
                    href="/dashboard/tasks/result?taskId=08cf4b9d-ec54-4b4a-be8f-6b27a17bd755"
                    className="text-sm font-medium text-blue-600 hover:text-blue-700 underline transition-colors"
                    target="_blank"
                  >
                    See an example Darcy ad →
                  </Link>
                  <Text className="text-zinc-600 text-sm leading-relaxed">
                    A real 10-second ad generated by Darcy. Opens in a new tab.
                  </Text>
                </div>
              </div>
            )}

            {/* Brand Context */}
            <div className="rounded-xl border border-zinc-200 bg-white p-4 sm:p-6 hover:shadow-md transition-all">
              <Subheading className="text-lg font-semibold text-zinc-800">
                Brand Context
              </Subheading>
              <div className="mt-3 space-y-2">
                <Link
                  href="/dashboard/settings/brand-context"
                  className="text-sm text-zinc-500 hover:text-blue-600 underline transition-colors"
                >
                  {worker?.catClass === 'wc-vi' || worker?.catClass === 'wc-au'
                    ? 'Configure your brand voice and visual identity →'
                    : 'Configure your brand voice →'}
                </Link>
                <Text className="text-zinc-600 text-sm leading-relaxed">
                  Your brand context is automatically injected into every task.
                </Text>
              </div>
            </div>

            {/* Previous Tasks */}
            <div className="rounded-xl border border-zinc-200 bg-white p-4 sm:p-6 shadow-sm hover:shadow-md transition-all">
              <Subheading className="text-lg font-semibold text-zinc-800">
                Previous Tasks
              </Subheading>
              <div className="mt-3">
                <Link
                  href="/dashboard/tasks"
                  className="text-sm text-zinc-500 hover:text-blue-600 underline transition-colors"
                >
                  View all tasks →
                </Link>
              </div>
            </div>
          </div>
        )}
      </div>

      {previewImage && typeof document !== 'undefined' && createPortal(
        <div
          className={`fixed inset-0 z-50 flex items-center justify-center bg-black/85 backdrop-blur-md p-4 transition-opacity duration-300 ease-out ${show ? 'opacity-100' : 'opacity-0'}`}
          onClick={closePreview}
        >
          <button
            className="absolute top-4 right-4 text-white/80 hover:text-white transition-colors p-2.5 rounded-full bg-white/10 hover:bg-white/20 hover:scale-105 active:scale-95 z-20 border border-white/10 cursor-pointer"
            onClick={closePreview}
          >
            <X className="size-6" />
          </button>

          {previewLoading && (
            <div className="absolute inset-0 flex items-center justify-center z-10 pointer-events-none">
              <Loader size={8} className="text-white" />
            </div>
          )}

          <div
            className={`relative max-w-[90%] md:max-w-4xl transition-all duration-300 ease-out ${show ? 'opacity-100 scale-100' : 'opacity-0 scale-95'}`}
            onClick={(e) => e.stopPropagation()}
          >
            <img
              src={previewImage}
              alt="Preview"
              onLoad={() => setPreviewLoading(false)}
              className={`max-w-full max-h-[85vh] object-contain rounded-2xl shadow-2xl select-none transition-opacity duration-300 ${previewLoading ? 'opacity-0' : 'opacity-100'}`}
            />
          </div>
        </div>,
        document.body
      )}
    </div>
  )
}

