'use client'

import React, { useState } from 'react'
import { Loader } from '@/components/loader'

interface AutoGeneratedImageOutputProps {
  output: {
    images?: Array<{
      source?: string
      url?: string
      expires_at?: string | number
    }>
    imageGeneration?: {
      status?: string
      expiresAt?: string
    }
  } | null
  workerSlug?: string
}

export default function AutoGeneratedImageOutput({ output, workerSlug }: AutoGeneratedImageOutputProps) {
  const [downloading, setDownloading] = useState(false)
  const [imageFailed, setImageFailed] = useState(false)
  const images = output?.images || []
  const autoImg = images.find((img: any) => img?.source === 'auto_text_image') || images[0]
  if (!autoImg?.url) return null

  const expiresAt = autoImg.expires_at || (output?.imageGeneration?.status === 'completed' ? output?.imageGeneration?.expiresAt : null)
  const expiryDate = expiresAt ? new Date(expiresAt).toLocaleDateString() : ''

  const handleDownload = async () => {
    if (!autoImg.url || downloading) return
    if (imageFailed) {
      alert('Image expired or unavailable. Please re-run the task to generate fresh images.')
      return
    }
    setDownloading(true)
    try {
      const res = await fetch(autoImg.url)
      const blob = await res.blob()
      const a = document.createElement('a')
      a.href = URL.createObjectURL(blob)
      a.download = `${workerSlug || 'ai'}-generated-image.png`
      a.click()
      URL.revokeObjectURL(a.href)
    } catch {
      window.open(autoImg.url, '_blank')
    } finally {
      setDownloading(false)
    }
  }

  return (
    <div className="p-3 md:p-6">
      <div className="overflow-hidden rounded-xl border border-zinc-950/[0.08] bg-white shadow-sm">
        <div className="flex flex-wrap items-center justify-between gap-4 border-b border-zinc-950/[0.06] px-5 py-4">
          <div>
            <p className="text-sm font-semibold text-zinc-950">AI-generated image</p>
            <p className="mt-0.5 text-xs text-zinc-500">
              Contextual image generated alongside this deliverable{expiryDate && ` · expires ${expiryDate}`}
            </p>
          </div>
          <button
            onClick={handleDownload}
            disabled={downloading}
            className="flex shrink-0 items-center gap-1.5 rounded-lg bg-blue-600 px-3 py-1.5 text-xs font-semibold text-white transition hover:bg-blue-700 disabled:opacity-60 cursor-pointer"
          >
            {downloading ? (
              <>
                <Loader size={3.5} className="!size-3.5 text-white" />
                Downloading…
              </>
            ) : (
              <>
                <svg width="12" height="12" viewBox="0 0 12 12" fill="none">
                  <path d="M6 1.5v6m0 0L4 5.5m2 2l2-2M2 9.5v.5a.5.5 0 00.5.5h7a.5.5 0 00.5-.5V9.5" stroke="currentColor" strokeWidth="1.25" strokeLinecap="round" strokeLinejoin="round" />
                </svg>
                Download
              </>
            )}
          </button>
        </div>
        <div className="flex bg-zinc-50/20 p-8 pt-4 justify-center">
          {imageFailed ? (
            <div className="flex flex-col items-center justify-center bg-zinc-50 p-8 rounded-lg min-h-[180px] text-center w-full">
              <span className="text-3xl mb-2">🖼️</span>
              <p className="text-sm font-medium text-zinc-600">Image expired or unavailable</p>
              {autoImg.url?.startsWith('https://') && (
                <a
                  href={autoImg.url}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="mt-2 text-xs text-blue-600 hover:underline font-medium"
                >
                  Try opening directly ↗
                </a>
              )}
            </div>
          ) : (
            <img
              src={autoImg.url}
              alt="AI-generated"
              onError={() => setImageFailed(true)}
              className="max-h-[500px] w-auto rounded-lg shadow-2xl ring-1 ring-zinc-950/10 object-contain"
            />
          )}
        </div>
      </div>
    </div>
  )
}
