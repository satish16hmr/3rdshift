export const maxDuration = 120;
import { NextRequest, NextResponse } from 'next/server'
import PptxGenJS from 'pptxgenjs'
import { requireAuth, supabaseAdmin } from '@/lib/api-auth'

function supabase() {
  return supabaseAdmin
}

interface Slide {
  title: string
  bullets: string[]
  speakerNotes?: string
}

/** Parse Claude's structured slide output into Slide objects */
function parseSlides(text: string): Slide[] {
  const slides: Slide[] = []

  // Split on "Slide N" or "SLIDE N" markers
  const blocks = text.split(/\n(?=(?:Slide|SLIDE)\s+\d+)/i).filter(Boolean)

  for (const block of blocks) {
    const lines = block.split('\n').map(l => l.trim()).filter(Boolean)
    if (!lines.length) continue

    // Title: first line or line after "Slide N:"
    let title = ''
    let bulletStart = 1
    const slideHeaderMatch = lines[0].match(/^(?:Slide|SLIDE)\s+\d+[:\s-]+(.+)/i)
    if (slideHeaderMatch) {
      title = slideHeaderMatch[1].trim()
    } else if (lines[1] && !lines[1].startsWith('-') && !lines[1].startsWith('•') && !lines[1].match(/^speaker notes/i)) {
      title = lines[0]
      bulletStart = 1
    } else {
      title = lines[0]
    }

    // Bullets and speaker notes
    const bullets: string[] = []
    let speakerNotes = ''
    let inNotes = false

    for (let i = bulletStart; i < lines.length; i++) {
      const line = lines[i]
      if (line.match(/^(?:speaker notes?|notes?)[:\s]/i)) {
        inNotes = true
        const notesText = line.replace(/^(?:speaker notes?|notes?)[:\s]*/i, '').trim()
        if (notesText) speakerNotes += notesText + ' '
        continue
      }
      if (inNotes) {
        speakerNotes += line + ' '
        continue
      }
      // Bullet point
      const cleaned = line.replace(/^[-•*]\s*/, '').trim()
      if (cleaned && !cleaned.match(/^Slide\s+\d+/i)) {
        bullets.push(cleaned)
      }
    }

    if (title) {
      slides.push({ title: title.replace(/\*\*/g, ''), bullets, speakerNotes: speakerNotes.trim() })
    }
  }

  // Fallback: if parsing failed, create a single slide from the whole text
  if (slides.length === 0) {
    slides.push({
      title: 'Presentation',
      bullets: text.split('\n').filter(l => l.trim()).slice(0, 10),
    })
  }

  return slides
}

export async function POST(req: NextRequest) {
  const auth = await requireAuth(req);
  if (auth instanceof NextResponse) return auth;
  const { userId, workspaceId } = auth;

  const db = supabase()
  let taskId: string | undefined

  try {
    const body = await req.json()
    taskId = body.taskId
    const slideText: string = body.slideText
    const presentationTitle: string = body.title || 'Presentation'

    if (!taskId || !slideText) {
      return NextResponse.json({ error: 'taskId and slideText required' }, { status: 400 })
    }

    // C09 fix: verify task ownership before generating or writing
    const { data: task, error: taskErr } = await db
      .from('tasks')
      .select('id, user_id, workspace_id')
      .eq('id', taskId)
      .single()

    if (taskErr || !task) {
      return NextResponse.json({ error: 'Task not found' }, { status: 404 })
    }

    const ownsTask = task.user_id === userId ||
      (task.workspace_id && task.workspace_id === workspaceId)

    if (!ownsTask) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 403 })
    }

    const slides = parseSlides(slideText)

    // Build .pptx
    const pptx = new PptxGenJS()
    pptx.layout = 'LAYOUT_16x9'

    // Theme colors
    const BRAND_BLUE = '2563EB'
    const DARK = '111113'
    const LIGHT_BG = 'F8F8FA'
    const WHITE = 'FFFFFF'
    const GRAY = '6B7280'

    // ── Title slide ──
    const titleSlide = pptx.addSlide()
    titleSlide.background = { color: DARK }
    titleSlide.addText(presentationTitle, {
      x: 0.5, y: 2.5, w: '90%', h: 1.2,
      fontSize: 36, bold: true, color: WHITE,
      align: 'center', fontFace: 'Calibri',
    })
    titleSlide.addText('Generated by 3rdShift · Mack, Presentation Builder', {
      x: 0.5, y: 4.0, w: '90%', h: 0.4,
      fontSize: 12, color: '9CA3AF',
      align: 'center', fontFace: 'Calibri',
    })
    // Blue accent bar at bottom
    titleSlide.addShape(pptx.ShapeType.rect, {
      x: 0, y: 6.8, w: '100%', h: 0.2,
      fill: { color: BRAND_BLUE },
      line: { color: BRAND_BLUE },
    })

    // ── Content slides ──
    for (let i = 0; i < Math.min(slides.length, 40); i++) {
      const slide = slides[i]
      const pSlide = pptx.addSlide()
      pSlide.background = { color: WHITE }

      // Blue header bar
      pSlide.addShape(pptx.ShapeType.rect, {
        x: 0, y: 0, w: '100%', h: 1.1,
        fill: { color: BRAND_BLUE },
        line: { color: BRAND_BLUE },
      })

      // Slide number
      pSlide.addText(`${i + 1}`, {
        x: 9.0, y: 0.15, w: 0.6, h: 0.5,
        fontSize: 11, color: 'BFDBFE',
        align: 'right', fontFace: 'Calibri',
      })

      // Title in header
      pSlide.addText(slide.title, {
        x: 0.4, y: 0.15, w: 8.5, h: 0.8,
        fontSize: 22, bold: true, color: WHITE,
        fontFace: 'Calibri', valign: 'middle',
      })

      // Bullet points
      if (slide.bullets.length > 0) {
        const bulletItems = slide.bullets.map(b => ({
          text: b,
          options: { fontSize: 16, color: DARK, bullet: { type: 'bullet' as const }, paraSpaceAfter: 6 },
        }))
        pSlide.addText(bulletItems, {
          x: 0.5, y: 1.3, w: 9.0, h: 5.0,
          fontFace: 'Calibri', valign: 'top',
        })
      }

      // Speaker notes
      if (slide.speakerNotes) {
        pSlide.addNotes(slide.speakerNotes)
      }

      // Subtle footer
      pSlide.addText(presentationTitle, {
        x: 0.4, y: 6.8, w: 7, h: 0.25,
        fontSize: 9, color: GRAY, fontFace: 'Calibri',
      })
    }

    // ── Thank you / end slide ──
    const endSlide = pptx.addSlide()
    endSlide.background = { color: BRAND_BLUE }
    endSlide.addText('Thank You', {
      x: 0.5, y: 2.5, w: '90%', h: 1.0,
      fontSize: 40, bold: true, color: WHITE,
      align: 'center', fontFace: 'Calibri',
    })
    endSlide.addText('Built with 3rdShift', {
      x: 0.5, y: 3.7, w: '90%', h: 0.4,
      fontSize: 14, color: 'BFDBFE',
      align: 'center', fontFace: 'Calibri',
    })

    // Generate buffer
    const pptxBuffer = await pptx.write({ outputType: 'nodebuffer' }) as Buffer

    // Upload to Supabase storage
    const expiresAt = new Date(Date.now() + 48 * 60 * 60 * 1000).toISOString()
    const fileName = `${taskId}/presentation-${Date.now()}.pptx`

    const { error: uploadError } = await db.storage
      .from('generated-files')
      .upload(fileName, pptxBuffer, {
        contentType: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
        upsert: false,
      })

    let downloadUrl = ''
    if (!uploadError) {
      const { data: signedData } = await db.storage
        .from('generated-files')
        .createSignedUrl(fileName, 48 * 60 * 60)
      downloadUrl = signedData?.signedUrl || ''
    } else {
      console.error('PPTX upload error:', uploadError)
    }

    // Build slide summary for result page preview
    const slideSummary = slides.map((s, i) => `Slide ${i + 1}: ${s.title}`).join('\n')

    // Update task
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    await (db.from('tasks') as any).update({
      output: {
        format: 'pptx',
        downloadUrl,
        fileName: `${presentationTitle.replace(/[^a-z0-9]/gi, '-')}.pptx`,
        storagePath: fileName,
        expiresAt,
        slideCount: slides.length + 2, // +title +end
        slideSummary,
        presentationTitle,
      },
      output_format: 'pptx',
      status: 'completed',
      completed_at: new Date().toISOString(),
    }).eq('id', taskId)

    return NextResponse.json({ success: true, taskId, slideCount: slides.length + 2, downloadUrl })
  } catch (err: unknown) {
    console.error('PPTX generation error:', err)
    const msg = err instanceof Error ? err.message : 'PPTX generation failed'
    if (taskId) {
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      await (supabase().from('tasks') as any).update({
        status: 'failed', error_message: msg,
      }).eq('id', taskId)
    }
    return NextResponse.json({ error: msg }, { status: 500 })
  }
}
