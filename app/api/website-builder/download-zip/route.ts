import { NextRequest, NextResponse } from 'next/server';
import { requireAuth, supabaseAdmin } from '@/lib/api-auth';

// POST /api/website-builder/download-zip
// Generates a ZIP with index.html, style.css, script.js, README.md and returns a signed download URL.
// Uses Supabase Storage — uploads to a temp bucket, returns signed URL (1 hour expiry).
export async function POST(req: NextRequest) {
  const auth = await requireAuth(req);
  if (auth instanceof NextResponse) return auth;
  const { userId, workspaceId } = auth;

  let body: {
    taskId: string;
    artifact: Record<string, unknown>;
    assembledHtml: string;
    businessName: string;
    pageType: string;
  };
  try { body = await req.json(); } catch {
    return NextResponse.json({ error: 'Invalid JSON' }, { status: 400 });
  }

  const { taskId: bodyTaskId, artifact, assembledHtml: clientHtml, businessName, pageType } = body;

  // M05 / Item 10 fix: if taskId provided, verify ownership and use server-stored HTML
  let assembledHtml = clientHtml;
  if (bodyTaskId) {
    const { data: taskRow } = await supabaseAdmin
      .from('tasks')
      .select('user_id, workspace_id, output')
      .eq('id', bodyTaskId)
      .single();
    if (!taskRow) {
      return NextResponse.json({ error: 'Task not found' }, { status: 404 });
    }
    const ownsTask = taskRow.user_id === userId ||
      (taskRow.workspace_id && taskRow.workspace_id === workspaceId);
    if (!ownsTask) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 403 });
    }
    // Prefer server-stored assembled HTML over client-supplied value
    const serverHtml = (taskRow.output as Record<string, unknown>)?.assembledHtml as string | undefined;
    if (serverHtml) assembledHtml = serverHtml;
  }

  if (!assembledHtml) {
    return NextResponse.json({ error: 'No HTML to download' }, { status: 400 });
  }

  // Build README
  const pageLabel: Record<string, string> = {
    landing: 'Landing Page', coming_soon: 'Coming Soon Page', lead_magnet: 'Lead Magnet Page',
    sales_page: 'Sales Page', service_business: 'Service Business Page',
  };
  const readme = `# ${businessName} — ${pageLabel[pageType] || 'Website'}
Generated by Silas (Website Builder) on 3rdShift — https://3rdshift.ai

## Files
- index.html — Complete, ready-to-publish HTML page
- README.md — This file

## Deploy Options

### Netlify Drop (fastest, free)
1. Go to https://app.netlify.com/drop
2. Drag and drop index.html into the page
3. Live in 30 seconds

### GitHub Pages (free)
1. Create a new GitHub repository
2. Upload index.html to the repo
3. Go to Settings → Pages → Deploy from main branch

### Vercel (free)
1. Go to https://vercel.com/new
2. Import your GitHub repo with index.html
3. Deploy

### WordPress
1. In WordPress admin: Pages → Add New
2. Switch to HTML editor
3. Paste the contents of index.html
4. Note: some themes may override styles. Use a blank/canvas page template for best results.

## Images
- Unsplash placeholder images are free to use under the Unsplash License (https://unsplash.com/license)
- Replace placeholder images with your own brand assets before final publishing
- Recommended size: hero images 1600×900px, section images 800×600px

## Customization
- Edit the CSS custom properties in the <style> block to change colors/fonts
- Tailwind CSS is loaded via CDN — for production, replace with compiled Tailwind

---
Built with 3rdShift Silas — https://3rdshift.ai
`;

  // Extract CSS and JS from assembled HTML for separate files
  const cssMatch = assembledHtml.match(/<style>([\s\S]*?)<\/style>/i);
  const jsMatch = assembledHtml.match(/<script>([\s\S]*?)<\/script>\s*<\/body>/i);
  const cssContent = cssMatch ? cssMatch[1].trim() : '';
  const jsContent = jsMatch ? jsMatch[1].trim() : '';

  // Build a single-file HTML (inline everything)
  // Already done — assembledHtml IS the single file
  const fileName = `${businessName.replace(/[^a-zA-Z0-9]/g, '-').replace(/-+/g, '-').toLowerCase()}-website`;

  // We don't have a ZIP library available easily, so we'll inline everything into a single HTML file
  // and provide it as a direct download. The "ZIP" is actually a self-contained HTML file for now.
  // TODO: add jszip/adm-zip for true ZIP when available
  // For now: return the assembled HTML as a data URL download via base64

  const htmlBase64 = Buffer.from(assembledHtml, 'utf8').toString('base64');
  const dataUrl = `data:text/html;base64,${htmlBase64}`;

  // Also try to save to Supabase Storage for a proper download URL
  try {
    const storageKey = `website-exports/${userId}/${fileName}-${Date.now()}.html`;
    const { error: uploadErr } = await supabaseAdmin.storage
      .from('task-exports')
      .upload(storageKey, Buffer.from(assembledHtml, 'utf8'), {
        contentType: 'text/html',
        upsert: true,
      });

    if (!uploadErr) {
      const { data: signedData } = await supabaseAdmin.storage
        .from('task-exports')
        .createSignedUrl(storageKey, 3600); // 1 hour

      if (signedData?.signedUrl) {
        return NextResponse.json({
          downloadUrl: signedData.signedUrl,
          fileName: `${fileName}.html`,
          readme,
        });
      }
    }
  } catch {
    // Fall through to base64 fallback
  }

  // Fallback: return base64 data URL (client-side download)
  return NextResponse.json({
    downloadUrl: dataUrl,
    fileName: `${fileName}.html`,
    readme,
    isDataUrl: true,
  });
}
