// Thumbnail card — browser canvas text overlay for Reed
// Uses named imports (useRef, useEffect, useState) already imported at top
// ---------------------------------------------------------------------------
function ThumbnailCard({ img, index, headlineText, workerSlug }) {
  const { showToast } = useToast()
  const canvasRef = useRef(null)
  const [ready, setReady] = useState(false)
  const [loadFailed, setLoadFailed] = useState(false)

  useEffect(() => {
    const canvas = canvasRef.current
    if (!canvas || !img.url) { setLoadFailed(true); return }
    function drawToCanvas(image) {
      const W = 1280, H = 720
      canvas.width = W
      canvas.height = H
      const ctx = canvas.getContext('2d')
      ctx.drawImage(image, 0, 0, W, H)

      const text = (headlineText || '').toUpperCase().trim()
      if (text) {
        const words = text.split(/\s+/).filter(Boolean).slice(0, 8)
        const mid = Math.ceil(words.length / 2)
        const line1 = words.slice(0, mid).join(' ')
        const line2words = words.slice(mid)
        const line2 = line2words.join(' ')
        const twoLines = line2.length > 0

        // Gradient bar
        const grad = ctx.createLinearGradient(0, H - 280, 0, H)
        grad.addColorStop(0, 'rgba(0,0,0,0)')
        grad.addColorStop(0.4, 'rgba(0,0,0,0.65)')
        grad.addColorStop(1, 'rgba(0,0,0,0.88)')
        ctx.fillStyle = grad
        ctx.fillRect(0, H - 280, W, 280)

        ctx.font = 'bold 96px "Arial Black", Arial, sans-serif'
        ctx.textAlign = 'center'
        ctx.textBaseline = 'bottom'
        ctx.lineJoin = 'round'
        ctx.lineWidth = 10

        if (twoLines) {
          ctx.strokeStyle = 'black'
          ctx.strokeText(line1, W / 2, H - 115)
          ctx.fillStyle = 'white'
          ctx.fillText(line1, W / 2, H - 115)
          ctx.strokeStyle = 'black'
          ctx.strokeText(line2, W / 2, H - 20)
          ctx.fillStyle = 'white'
          ctx.fillText(line2, W / 2, H - 20)
        } else {
          ctx.strokeStyle = 'black'
          ctx.strokeText(line1, W / 2, H - 20)
          ctx.fillStyle = 'white'
          ctx.fillText(line1, W / 2, H - 20)
        }
      }
      setReady(true)
    }

    // Try with CORS first (enables canvas export for download).
    // If CORS fails, retry without it so the image at least displays.
    const image = new window.Image()
    image.crossOrigin = 'anonymous'
    image.onload = () => drawToCanvas(image)
    image.onerror = () => {
      // Retry without crossOrigin — canvas will be tainted but image will render
      const fallback = new window.Image()
      fallback.onload = () => drawToCanvas(fallback)
      fallback.onerror = () => { setLoadFailed(true); setReady(true) }
      fallback.src = img.url
    }
    image.src = img.url
  }, [img.url, headlineText])

  const [downloading, setDownloading] = useState(false)
  const handleDownload = () => {
    const canvas = canvasRef.current
    if (!canvas) {
      window.open(img.url, '_blank')
      showToast?.({ title: 'Download completed successfully!', variant: 'success' })
      return
    }
    setDownloading(true)
    try {
      canvas.toBlob(blob => {
        if (!blob) {
          window.open(img.url, '_blank')
          showToast?.({ title: 'Download completed successfully!', variant: 'success' })
          setDownloading(false)
          return
        }
        const a = document.createElement('a')
        a.href = URL.createObjectURL(blob)
        a.download = `${workerSlug}-thumbnail-${index + 1}.png`
        a.click()
        URL.revokeObjectURL(a.href)
        showToast?.({ title: 'Download completed successfully!', variant: 'success' })
        setDownloading(false)
      }, 'image/png')
    } catch {
      window.open(img.url, '_blank')
      showToast?.({ title: 'Download failed. Please try again.', variant: 'error' })
      setDownloading(false)
    }
  }

  return (
    <div className="overflow-hidden rounded-xl border border-zinc-950/[0.08] bg-zinc-100 shadow-sm">
      {loadFailed ? (
        <div className="flex flex-col items-center justify-center bg-zinc-50 px-4 py-8" style={{ aspectRatio: '16/9' }}>
          <span className="text-3xl mb-2">🖼️</span>
          <p className="text-sm font-medium text-zinc-600">Image unavailable</p>
          <p className="text-xs text-zinc-400 mt-1 text-center">This image may have expired. Try downloading directly.</p>
          <a
            href={img.url}
            target="_blank"
            rel="noopener noreferrer"
            className="mt-3 flex items-center gap-1.5 rounded-lg bg-blue-600 px-3 py-1.5 text-xs font-semibold text-white transition hover:bg-blue-700"
          >
            Open original ↗
          </a>
        </div>
      ) : (
        <canvas ref={canvasRef} className="w-full block" style={{ aspectRatio: '16/9' }} />
      )}
      <div className="flex items-center justify-between px-4 py-3 border-t border-zinc-950/[0.06] bg-white">
        <Text className="text-xs text-zinc-400">Option {index + 1}</Text>
        <button
          onClick={handleDownload}
          disabled={(!ready && !loadFailed) || downloading}
          className="flex items-center cursor-pointer gap-1.5 rounded-lg bg-blue-600 px-3 py-1.5 text-xs font-semibold text-white transition hover:bg-blue-700 disabled:opacity-40"
        >
          {downloading ? (
            <>
              <span className="size-3 animate-spin rounded-full border border-white border-t-transparent" />
              Downloading…
            </>
          ) : (
            <>
              <svg width="12" height="12" viewBox="0 0 12 12" fill="none">
                <path d="M6 1.5v6m0 0L4 5.5m2 2l2-2M2 9.5v.5a.5.5 0 00.5.5h7a.5.5 0 00.5-.5V9.5" stroke="currentColor" strokeWidth="1.25" strokeLinecap="round" strokeLinejoin="round" />
              </svg>
              Download
            </>
          )}
        </button>
      </div>
    </div>
  )
}

