function createImageUnavailableFallback(imageUrl, className = 'flex flex-col items-center justify-center bg-zinc-50 px-4 py-12', minHeight = '180px') {
  const fallback = document.createElement('div')
  fallback.className = className
  fallback.style.minHeight = minHeight

  const icon = document.createElement('span')
  icon.textContent = '🖼️'
  icon.style.fontSize = '2rem'
  icon.style.marginBottom = '8px'
  fallback.appendChild(icon)

  const message = document.createElement('p')
  message.textContent = 'Image expired or unavailable'
  message.style.fontSize = '13px'
  message.style.color = '#52525b'
  message.style.fontWeight = '500'
  fallback.appendChild(message)

  try {
    const parsed = new URL(imageUrl, window.location.href)
    if (parsed.protocol === 'https:') {
      const link = document.createElement('a')
      link.textContent = 'Try opening directly ↗'
      link.setAttribute('href', parsed.toString())
      link.setAttribute('target', '_blank')
      link.setAttribute('rel', 'noopener noreferrer')
      link.style.marginTop = '8px'
      link.style.fontSize = '12px'
      link.style.color = '#2563eb'
      link.style.textDecoration = 'underline'
      fallback.appendChild(link)
    }
  } catch {
    // Invalid image URL: omit the direct-open link rather than rendering unsafe markup.
  }

  return fallback
}

